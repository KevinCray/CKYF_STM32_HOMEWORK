void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
  if (GPIO_Pin == GPIO_PIN_12)
  {
    key_edge_tick = HAL_GetTick();  //记录边沿触发时间
    key_edge_pending = 1;           //传到主循环任务函数处理
  }
}

/** 
 * @brief 按键扫描函数喵
*/

void key_scanning(void)
{
  uint32_t present_time = HAL_GetTick();

  if (key_edge_pending)
  {
    if ((present_time - key_edge_tick)>=20)
    {
      key_edge_pending = 0;
      GPIO_PinState PIN_STATE = HAL_GPIO_ReadPin(BUTTON_GPIO_Port, BUTTON_Pin);
      uint8_t new_pressed = (PIN_STATE == GPIO_PIN_RESET);

      if (new_pressed != press_status)
      {
        press_status = new_pressed;

        if (press_status)
        {
          press_tick = present_time;
          long_pressed = 0;
        }
        else
        {
          if (!long_pressed)
          {
            led_fast = 0;
            led_status = ! led_status;
          }
          
        }
        
      }
      
    }
    
  }
  
  if (press_status && !long_pressed && HAL_GPIO_ReadPin(BUTTON_GPIO_Port, BUTTON_Pin) == GPIO_PIN_RESET && (present_time - press_tick) >= 1000)
  {
    long_pressed = 1;
    led_fast = ! led_fast;

    blink_tick = present_time;
  }
  
}

/**
 * @brief led状态切换函数喵喵喵
 */
void led_process(void)
{
  uint32_t present_time = HAL_GetTick();
  
  if (led_fast)
  {
    if ((present_time - blink_tick) >= 200)
    {
      blink_tick = present_time;
      led_status = ! led_status;
    }
  }

  HAL_GPIO_WritePin(LED1_GPIO_Port, LED1_Pin, led_status ? GPIO_PIN_RESET : GPIO_PIN_SET);
}

void breath_led(void)
{
  uint32_t present_time = HAL_GetTick();

  if ((present_time - breath_tick) >= 10) //每10ms更新亮度
  {
    breath_tick = present_time;   //更新时间

    int32_t next_duty = (int32_t)breath_duty + breath_dir * 10;

    if (breath_duty >= 1000)
    {
      next_duty = 1000;
      breath_dir = -1;
    }
    else if (next_duty <= 1000)
    {
      next_duty = 0;
      breath_dir = 1;
    }
    
    breath_duty = (uint16_t) next_duty; //更新占空比数值

    __HAL_TIM_SET_COMPARE(&htim3,TIM_CHANNEL_1,breath_duty);
  } 
}
